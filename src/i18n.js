/* pick the text for a language: 'en', 'ar', or 'both' (English · عربي) */
export function pickLang(en, ar, lang){
  if(lang==='ar') return ar || en;
  if(lang==='both') return ar && ar!==en ? `${en} · ${ar}` : en;
  return en;
}
export const tr = (key, lang) => pickLang(UI[key][0], UI[key][1], lang);
